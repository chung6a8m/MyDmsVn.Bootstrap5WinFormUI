namespace MyDmsVn.Bootstrap5WinFormUI.Theme;

/// <summary>
/// Identifies the visual mode used by a <see cref="BootstrapTheme"/>.
/// </summary>
public enum BootstrapThemeMode
{
    /// <summary>
    /// Uses light application surfaces and dark foreground text.
    /// </summary>
    Light = 0,

    /// <summary>
    /// Uses dark application surfaces and light foreground text.
    /// </summary>
    Dark = 1
}
