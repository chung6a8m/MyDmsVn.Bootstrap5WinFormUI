namespace MyDmsVn.Bootstrap5WinFormUI.Formatting;

/// <summary>Specifies the structural hour range used by time formatting.</summary>
public enum BootstrapTimeFormat
{
    /// <summary>Uses hours from 00 through 23.</summary>
    TwentyFourHour,
    /// <summary>Uses hours from 01 through 12 without adding an AM/PM suffix.</summary>
    TwelveHour
}
