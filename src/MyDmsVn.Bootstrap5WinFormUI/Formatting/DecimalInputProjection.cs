using System;
using System.Collections.Generic;
using System.Text;

namespace MyDmsVn.Bootstrap5WinFormUI.Formatting;

/// <summary>A pure display projection and its candidate/display boundary map.</summary>
public sealed class DecimalProjectionResult
{
    internal DecimalProjectionResult(string candidateText, string displayText, int[] before, int[] after, int[] displayToCandidate, bool[] generated)
    {
        CandidateText = candidateText;
        DisplayText = displayText;
        _before = before;
        _after = after;
        _displayToCandidate = displayToCandidate;
        _generated = generated;
        _isIdentity = Array.IndexOf(generated, true) < 0;
    }

    private readonly int[] _before;
    private readonly int[] _after;
    private readonly int[] _displayToCandidate;
    private readonly bool[] _generated;
    private readonly bool _isIdentity;

    /// <summary>The exact pending lexical input, unchanged.</summary>
    public string CandidateText { get; }
    /// <summary>Display text with only reversible generated grouping.</summary>
    public string DisplayText { get; }
    /// <summary>Whether display is an unmodified candidate.</summary>
    public bool IsIdentity => _isIdentity;

    /// <summary>Maps a candidate boundary to display; choose either side of any generated separator at that boundary.</summary>
    public int ToDisplayBoundary(int candidateBoundary, bool afterGeneratedSeparator = true)
    {
        if (candidateBoundary < 0 || candidateBoundary >= _before.Length) throw new ArgumentOutOfRangeException(nameof(candidateBoundary));
        return afterGeneratedSeparator ? _after[candidateBoundary] : _before[candidateBoundary];
    }

    /// <summary>Maps a display boundary back to the exact candidate boundary.</summary>
    public int ToCandidateBoundary(int displayBoundary)
    {
        if (displayBoundary < 0 || displayBoundary >= _displayToCandidate.Length) throw new ArgumentOutOfRangeException(nameof(displayBoundary));
        return _displayToCandidate[displayBoundary];
    }

    /// <summary>True only for a character generated by this projection, never pasted source text.</summary>
    public bool IsGeneratedCharacter(int displayIndex)
    {
        if (displayIndex < 0 || displayIndex >= _generated.Length) throw new ArgumentOutOfRangeException(nameof(displayIndex));
        return _generated[displayIndex];
    }
}

/// <summary>Pure, reversible display projection for valid ungrouped decimal candidates.</summary>
public static class DecimalInputProjection
{
    /// <summary>Projects the exact pending text without accepting or mutating it.</summary>
    public static DecimalProjectionResult Project(string pendingText, DecimalInputProfile profile)
    {
        if (pendingText == null) throw new ArgumentNullException(nameof(pendingText));
        if (profile == null) throw new ArgumentNullException(nameof(profile));
        if (DecimalInputParser.TryParsePending(pendingText, profile).State != InputParseState.Valid ||
            pendingText.Length == 0 || !string.Equals(pendingText, pendingText.Trim(), StringComparison.Ordinal))
            return Identity(pendingText);

        var format = profile.Culture.NumberFormat;
        var group = format.NumberGroupSeparator;
        if (string.IsNullOrEmpty(group) || string.Equals(group, format.NumberDecimalSeparator, StringComparison.Ordinal))
            return Identity(pendingText);
        foreach (var character in group) if (character >= '0' && character <= '9') return Identity(pendingText);

        var integerStart = 0;
        if (!string.IsNullOrEmpty(format.NegativeSign) && pendingText.StartsWith(format.NegativeSign, StringComparison.Ordinal))
            integerStart = format.NegativeSign.Length;
        else if (!string.IsNullOrEmpty(format.PositiveSign) && pendingText.StartsWith(format.PositiveSign, StringComparison.Ordinal))
            integerStart = format.PositiveSign.Length;
        var integerEnd = integerStart;
        while (integerEnd < pendingText.Length && pendingText[integerEnd] >= '0' && pendingText[integerEnd] <= '9')
            integerEnd++;
        if (integerEnd == integerStart || integerEnd - integerStart <= 3 ||
            integerEnd < pendingText.Length && integerEnd + format.NumberDecimalSeparator.Length == pendingText.Length)
            return Identity(pendingText);

        var sizes = format.NumberGroupSizes;
        if (sizes.Length == 0 || sizes[0] <= 0) return Identity(pendingText);
        var insert = new bool[pendingText.Length + 1];
        var remaining = integerEnd - integerStart;
        var sizeIndex = 0;
        var size = sizes[sizeIndex];
        var groupCount = 0;
        while (size > 0 && remaining > size)
        {
            remaining -= size;
            insert[integerStart + remaining] = true;
            groupCount++;
            if (sizeIndex + 1 < sizes.Length) size = sizes[++sizeIndex];
        }
        if (groupCount == 0) return Identity(pendingText);

        var before = new int[pendingText.Length + 1];
        var after = new int[pendingText.Length + 1];
        var displayToCandidate = new List<int>(pendingText.Length + groupCount * group.Length + 1) { 0 };
        var generated = new List<bool>(pendingText.Length + groupCount * group.Length);
        var display = new StringBuilder(pendingText.Length + groupCount * group.Length);
        for (var candidateBoundary = 0; candidateBoundary <= pendingText.Length; candidateBoundary++)
        {
            before[candidateBoundary] = display.Length;
            if (insert[candidateBoundary])
            {
                foreach (var character in group)
                {
                    display.Append(character);
                    generated.Add(true);
                    displayToCandidate.Add(candidateBoundary);
                }
            }
            after[candidateBoundary] = display.Length;
            if (candidateBoundary == pendingText.Length) break;
            display.Append(pendingText[candidateBoundary]);
            generated.Add(false);
            displayToCandidate.Add(candidateBoundary + 1);
        }
        return new DecimalProjectionResult(pendingText, display.ToString(), before, after, displayToCandidate.ToArray(), generated.ToArray());
    }

    private static DecimalProjectionResult Identity(string pendingText)
    {
        var boundaries = new int[pendingText.Length + 1];
        for (var i = 0; i < boundaries.Length; i++) boundaries[i] = i;
        return new DecimalProjectionResult(pendingText, pendingText, boundaries, boundaries, boundaries, new bool[pendingText.Length]);
    }
}
