namespace MyDmsVn.Bootstrap5WinFormUI.Controls;

/// <summary>Specifies whether a modal has a backdrop and whether it dismisses the dialog.</summary>
public enum BootstrapModalBackdropMode
{
    /// <summary>Does not create a backdrop window.</summary>
    None,
    /// <summary>Dismisses the modal when the backdrop is clicked.</summary>
    Dismissible,
    /// <summary>Shows a backdrop that does not dismiss the modal.</summary>
    Static
}
