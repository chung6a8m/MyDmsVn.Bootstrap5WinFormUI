namespace MyDmsVn.Bootstrap5WinFormUI.Controls;

/// <summary>
/// Defines the Bootstrap-inspired visual treatment used for tab headers.
/// </summary>
public enum BootstrapTabStyle
{
    /// <summary>
    /// Uses bordered tab headers with rounded top corners.
    /// </summary>
    Tabs = 0,

    /// <summary>
    /// Uses rounded pill headers.
    /// </summary>
    Pills = 1,

    /// <summary>
    /// Uses a minimal header with an accent underline for the selected tab.
    /// </summary>
    Underline = 2
}
