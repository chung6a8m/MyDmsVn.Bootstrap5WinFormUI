namespace MyDmsVn.Bootstrap5WinFormUI.Controls;

/// <summary>Specifies the Bootstrap-inspired preferred width of a modal dialog.</summary>
public enum BootstrapModalSize
{
    /// <summary>Uses the small preferred width.</summary>
    Small,
    /// <summary>Uses the default preferred width.</summary>
    Default,
    /// <summary>Uses the large preferred width.</summary>
    Large,
    /// <summary>Uses the extra-large preferred width.</summary>
    ExtraLarge,
    /// <summary>Uses the inherited native <c>Size</c>/<c>ClientSize</c> request.</summary>
    Custom
}
