namespace MyDmsVn.Bootstrap5WinFormUI.Controls;

/// <summary>
/// Defines whether a <c>BootstrapSelect</c> permits one or multiple logical selections.
/// </summary>
public enum BootstrapSelectMode
{
    /// <summary>
    /// At most one logical value can be selected.
    /// </summary>
    Single = 0,

    /// <summary>
    /// Multiple logical values can be selected in selection order.
    /// </summary>
    Multiple = 1
}
