namespace MyDmsVn.Bootstrap5WinFormUI.Controls;

/// <summary>
/// Defines the corner in which a <see cref="BootstrapToastContainer"/> stacks owned toast notifications.
/// </summary>
public enum BootstrapToastPlacement
{
    /// <summary>Stacks notifications from the top-left corner downward.</summary>
    TopLeft,

    /// <summary>Stacks notifications from the top-right corner downward.</summary>
    TopRight,

    /// <summary>Stacks notifications from the bottom-left corner upward.</summary>
    BottomLeft,

    /// <summary>Stacks notifications from the bottom-right corner upward.</summary>
    BottomRight
}
