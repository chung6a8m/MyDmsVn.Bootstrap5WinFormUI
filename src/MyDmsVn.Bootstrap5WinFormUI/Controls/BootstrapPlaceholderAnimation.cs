namespace MyDmsVn.Bootstrap5WinFormUI.Controls;

/// <summary>
/// Defines the visual presentation applied to a placeholder.
/// </summary>
public enum BootstrapPlaceholderAnimation
{
    /// <summary>Displays a static placeholder.</summary>
    None,

    /// <summary>Cycles the opacity of the whole placeholder.</summary>
    Glow,

    /// <summary>Moves a subtle opacity trough across the placeholder.</summary>
    Wave
}
